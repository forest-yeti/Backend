defmodule BlockPoker.Engine.Variant do
  @moduledoc """
  Всё, чем один вид покера отличается от другого, живёт за этим behaviour.

  Ни `Showdown`, ни `Equity`, ни `HandRank` не содержат `case` по типу игры:
  ветвление по *виду* покера допустимо ровно в одном месте — при выборе
  модуля варианта. Это продолжение §3 CLAUDE.md («ветвление по правилам
  игры вне engine запрещено») внутрь самого engine.

  Критерий, по которому behaviour считается верным: новый вид покера — это
  один новый модуль и строка в реестре, и ноль правок в существующих файлах.
  Проверяется искусственным вариантом в `test/support`.
  """

  alias BlockPoker.Engine.{BettingStructure, Card}

  @doc "Идентификатор варианта; по нему вариант достаётся из реестра."
  @callback id() :: atom()

  @doc "Состав колоды. Short Deck отдаёт 36 карт, Hold'em — 52."
  @callback deck() :: [Card.t()]

  @doc "Сколько карманных карт у игрока."
  @callback hole_cards_count() :: pos_integer()

  @doc "Сколько карт на полном борде. У китайского покера борда нет — 0."
  @callback board_size() :: non_neg_integer()

  @doc """
  Как из карт игрока и борда собираются кандидаты на пятёрку.
  Hold'em — любые 5 из 7, Omaha — ровно 2 из руки и ровно 3 с борда.
  """
  @callback candidate_hands(hole :: [Card.t()], board :: [Card.t()]) :: [[Card.t()]]

  @doc "Порядок силы категорий от младшей к старшей именно этого варианта."
  @callback category_order() :: [atom()]

  @doc """
  Последовательности рангов, считающиеся стритом. Первый ранг списка —
  тот, по которому стрит сравнивается: у `A2345` это пятёрка.
  """
  @callback straight_sequences() :: [[0..12]]

  @doc """
  Как за столом собираются вынужденные ставки (`Engine.BettingStructure`).

  Структура принадлежит виду покера, а не шаблону стола: холдем играют на
  блайндах, Short Deck — на анте кнопки. Свободная комбинация «любой вариант
  на любой структуре» породила бы столы, которых не существует в природе,
  и каждый пришлось бы поддерживать.
  """
  @callback betting_structure() :: BettingStructure.t()

  @doc "Делится ли банк и по какой второй шкале."
  @callback pot_split() :: :high | {:hi_lo, low_evaluator :: module()}

  @type t :: module()
end
