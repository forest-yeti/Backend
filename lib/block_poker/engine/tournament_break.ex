defmodule BlockPoker.Engine.TournamentBreak do
  @moduledoc """
  Перерывы турнира: когда останавливаться и на сколько.

  **Правило рума, а не настройка турнира: каждый час в `XX:55` турнир
  уходит на пятиминутный перерыв.** Константы живут здесь, полей в
  шаблоне нет вовсе.

  Отсчёт — по **стенным часам** рума, а не от старта турнира. Поэтому
  турнир, начавшийся в 21:30, отдыхает уже через 25 минут, а не через 55.
  Так сделано ради мультитейблера: игрок за четырьмя турнирами разных
  стартов получает один общий перерыв, а не четыре вразнобой, между
  которыми нельзя отойти.

  ## Что из этого следует

  * **Перерыв синхронный.** В `XX:55` новые раздачи не начинаются нигде;
    стол, закончивший раньше, стоит и ждёт остальных — лишняя раздача
    уехала бы в перерыв.
  * **Пять минут отсчитываются от последней доигранной раздачи**, а не
    от `XX:55`. Значит, перерыв начинается позже ровно настолько, сколько
    доигрывалась самая долгая раздача, но длится всегда полные пять минут:
    иначе игрок за медленным столом получил бы перерыв короче остальных,
    а перерыв нужен ему физически, а не номинально.
  * **Таймер уровня на перерыве стоит.** Каждый уровень честно получает
    свои `duration_seconds` **игрового** времени: перерыв — это не часть
    уровня, а изъятие из него. Платой становится дрейф сетки уровней
    относительно часов примерно на пять минут за час игры, и это
    нормально: игрок смотрит на «до следующего уровня», а не сверяет
    блайнды с настенными часами.
  * **Финальный стол перерывов не отменяет.** Иначе двое финалистов
    играли бы без отдыха неограниченно.

  Модуль чистый: момент времени на входе, момент времени на выходе.
  """

  @minute_of_hour 55
  @duration_seconds 300

  @doc "Минута часа, в которую турнир перестаёт раздавать."
  @spec minute_of_hour() :: 0..59
  def minute_of_hour, do: @minute_of_hour

  @doc "Длительность перерыва в секундах — полная и несокращаемая."
  @spec duration_seconds() :: pos_integer()
  def duration_seconds, do: @duration_seconds

  @doc "Длительность перерыва в миллисекундах: таймеры живут в них."
  @spec duration_ms() :: pos_integer()
  def duration_ms, do: @duration_seconds * 1000

  @doc """
  Ближайший момент, когда турнир обязан перестать раздавать.

  Строго **после** `now`: перерыв, только что закончившийся, не должен
  начаться снова той же секундой.
  """
  @spec next_stop(DateTime.t()) :: DateTime.t()
  def next_stop(%DateTime{} = now) do
    candidate = %{now | minute: @minute_of_hour, second: 0, microsecond: {0, 0}}

    if DateTime.compare(candidate, now) == :gt do
      candidate
    else
      DateTime.add(candidate, 3600, :second)
    end
  end

  @doc """
  Пора ли останавливаться: наступил ли момент `XX:55`.

  Отдельная функция, потому что решение принимается на **завершении
  раздачи**, а не по таймеру: таймер только будит турнир, а раздавать
  ли следующую руку, решает этот предикат.
  """
  @spec stop?(DateTime.t(), DateTime.t()) :: boolean()
  def stop?(%DateTime{} = now, %DateTime{} = stop_at) do
    DateTime.compare(now, stop_at) != :lt
  end

  @doc """
  Сколько миллисекунд ждать до ближайшей остановки.

  Ноль означает «уже пора»: отрицательного ожидания не бывает, а
  просроченный таймер обязан сработать немедленно.
  """
  @spec until_stop_ms(DateTime.t()) :: non_neg_integer()
  def until_stop_ms(%DateTime{} = now) do
    max(DateTime.diff(next_stop(now), now, :millisecond), 0)
  end

  @doc """
  Момент конца перерыва: пять минут от того мгновения, когда закончилась
  **последняя** идущая раздача.

  Аргумент — именно этот момент, а не `XX:55`: перерыв не сокращается
  на то, что раздача затянулась.
  """
  @spec ends_at(DateTime.t()) :: DateTime.t()
  def ends_at(%DateTime{} = all_hands_finished_at) do
    DateTime.add(all_hands_finished_at, @duration_seconds, :second)
  end
end
