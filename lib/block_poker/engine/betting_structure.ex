defmodule BlockPoker.Engine.BettingStructure do
  @moduledoc """
  Как за столом собираются вынужденные ставки — и всё, что из этого следует.

  Блайнды и анте кнопки отличаются не «размером ставки», а четырьмя вещами
  сразу: кто и сколько платит до первой карты, какая из этих ставок живая,
  кто говорит первым на префлопе и от какого номинала считается минимальный
  рейз. Раньше все четыре ответа были зашиты в `Engine.Hand`; теперь они
  живут здесь, а раздача их только спрашивает.

  Правило то же, что и у `Engine.Variant`: ветвление по структуре допустимо
  ровно в одном месте — при выборе модуля. Никаких `case` по `:blinds` /
  `:button_ante` в раздаче, комнате и тем более в транспорте.

  Структуру выбирает вариант игры (`Variant.betting_structure/0`): холдем
  играется на блайндах, Short Deck — на анте кнопки. Отдельного поля в
  шаблоне стола нет намеренно — комбинаций, которых не существует в природе,
  быть не должно.

  Behaviour чистый: на входе `HandSetup` (числа и места), на выходе — данные.
  """

  alias BlockPoker.Engine.HandSetup

  @typedoc """
  Одна вынужденная ставка.

  `live?` — главное поле. Живая ставка становится ставкой круга: её надо
  уравнять, и поставивший сохраняет право голоса, когда очередь дойдёт до
  него. Мёртвая уходит в банк, ставкой не считается и права чека не даёт.
  Большой блайнд и дополнительное анте кнопки живые; обычное анте — нет.

  Два ключа необязательны, и по умолчанию они описывают поведение блайнда:
  `option?` (по умолчанию `true`) — сохраняет ли поставивший право голоса,
  когда очередь дойдёт до него; `top_up?` (по умолчанию `false`) — считать
  ли сумму итогом вложенного, а не добавкой к нему. Оба нужны страддлу
  (`Engine.Straddle`), который структурой ставок не является, но ставится
  тем же механизмом.
  """
  @type forced_bet :: %{
          required(:seat) => pos_integer(),
          required(:kind) =>
            :ante | :button_ante | :small_blind | :big_blind | :straddle | :bomb_pot_ante,
          required(:amount) => non_neg_integer(),
          required(:live?) => boolean(),
          optional(:option?) => boolean(),
          optional(:top_up?) => boolean()
        }

  @typedoc """
  Номиналы стола — всё, что нужно знать о деньгах, чтобы назвать базовую
  единицу. `HandSetup` этому виду соответствует, поэтому `bet_unit/1`
  спрашивают и раздача, и шаблон комнаты, которому раздачи ещё нет.
  """
  @type limits :: %{
          required(:big_blind) => non_neg_integer(),
          required(:ante) => non_neg_integer()
        }

  @type t :: module()

  @doc "Идентификатор структуры: уходит в снапшот стола и в логи."
  @callback id() :: atom()

  @doc """
  Вынужденные ставки раздачи в порядке постановки.

  Суммы возвращаются полными; урезать их по стеку — дело раздачи, она одна
  знает, сколько у игрока осталось после предыдущей ставки.
  """
  @callback forced_bets(HandSetup.t()) :: [forced_bet()]

  @doc """
  Место, **после** которого начинается торговля на префлопе.

  Возвращается именно последнее место, а не первое: между ним и первым
  говорящим могут стоять игроки, которым нечем отвечать (олл-ин с анте),
  и пропускать их умеет только сама раздача.

  Блайнды — большой блайнд, анте кнопки — кнопка. Постфлопный порядок
  общий для всех структур (первым говорит ближайший от кнопки) и сюда
  не относится.
  """
  @callback last_to_act_preflop(HandSetup.t()) :: pos_integer() | nil

  @doc """
  Номинал, от которого считаются минимальная ставка и минимальный рейз.
  Блайнды — большой блайнд, анте кнопки — анте.
  """
  @callback bet_unit(HandSetup.t() | limits()) :: non_neg_integer()

  @doc """
  Правила входа севшего игрока: ждёт ли он своей очереди платить и может ли
  войти за взнос. У блайндов это `Engine.EntryRules`, у анте кнопки —
  `Engine.EntryRules.Immediate`: ждать нечего, все платят каждую раздачу.
  """
  @callback entry_rules() :: module()
end
