defmodule BlockPoker.Engine.BombPot do
  @moduledoc """
  Бомб-пот: раздача, в которой префлопа нет.

  Все участники платят одинаковый взнос **до карт**, флоп открывается сразу,
  и торговля начинается с него. Смысл механики в том, что она убирает
  единственную улицу, где решение принимается вслепую и почти всегда
  одинаково («сбросил»), и делает банк, за который стоит играть, из денег
  всего стола поровну — а не из двух худших позиций, как блайнды.

  Механика — свойство **раздачи**, а не стола: за одним и тем же столом
  бомб-пот выпадает с заданным шансом, и выпадение решается броском ДО
  того, как игрокам показали хоть одну карту.

  ## Шанс

  Хранится и считается в целых десятитысячных (`scale/0`): `500` — это 5%,
  `10_000` — каждая раздача. Дробей здесь нет намеренно, по тому же правилу,
  что и у денег (§5 CLAUDE.md): `0.1` в конфиге и `0.1` после round-trip
  через БД и JSON — не всегда одно и то же число, а шанс обязан быть ровно
  тем, что задал оператор.

  Бросок берёт `Engine.Rng` и возвращает новое состояние: раздача обязана
  воспроизводиться по seed целиком, включая ответ на вопрос «а был ли это
  бомб-пот» — иначе тот же seed давал бы разные раздачи.

  Модуль чистый: числа на входе, числа на выходе.
  """

  alias BlockPoker.Engine.Rng

  @typedoc "Бомб-пот этой раздачи: взнос в фишках, одинаковый для всех."
  @type t :: %{ante: pos_integer()}

  # Десятитысячные: 1 = 0.01%. Той же ценой хранится рейк (`rake_percent`),
  # и заводить вторую шкалу процентов в проекте незачем.
  @scale 10_000

  @doc "Знаменатель шкалы шанса: `chance / scale()` — вероятность раздачи."
  @spec scale() :: pos_integer()
  def scale, do: @scale

  @doc """
  Выпал ли бомб-пот. `0` — механики за столом нет, `scale()` — каждая
  раздача; оба края решаются без обращения к RNG, чтобы выключенный
  бомб-пот не сдвигал последовательность случайных чисел.
  """
  @spec roll(Rng.t(), non_neg_integer()) :: {boolean(), Rng.t()}
  def roll(rng, chance) when is_integer(chance) and chance <= 0, do: {false, rng}
  def roll(rng, chance) when is_integer(chance) and chance >= @scale, do: {true, rng}

  def roll(rng, chance) when is_integer(chance) do
    {value, rng} = Rng.uniform_below(rng, @scale)
    {value < chance, rng}
  end

  @doc """
  Взнос в фишках. Задаётся в номиналах стола, а не в фишках, ровно по той
  же причине, что и бай-ин: «два номинала» переживает смену лимита, а
  «двадцать фишек» — нет.
  """
  @spec ante(non_neg_integer(), pos_integer()) :: non_neg_integer()
  def ante(bet_unit, units), do: bet_unit * units

  @doc """
  Шанс словами — то, что клиент подписывает в строке лобби («BP 5%»).

  Считается здесь, а не во view: деление десятитысячных на проценты — это
  арифметика над доменным значением, и её место в ядре (§3 CLAUDE.md).
  """
  @spec percent_label(non_neg_integer()) :: String.t()
  def percent_label(chance) when is_integer(chance) and chance >= 0 do
    whole = div(chance, 100)

    case rem(chance, 100) do
      0 -> Integer.to_string(whole)
      tenths when rem(tenths, 10) == 0 -> "#{whole}.#{div(tenths, 10)}"
      hundredths -> "#{whole}.#{String.pad_leading(Integer.to_string(hundredths), 2, "0")}"
    end
  end
end
