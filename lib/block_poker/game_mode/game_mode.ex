defmodule BlockPoker.GameMode do
  @moduledoc """
  Шов между комнатой и раздачей (§9 задачи 3).

  Наблюдение, на котором держится разделение: **сама раздача везде одинакова,
  различия живут между раздачами.** Порядок хода, набор решений, min-raise,
  сайд-поты — один и тот же код для кэша и турнира. Различаются вещи вокруг:
  откуда фишки, что значит проигранный стек, можно ли встать, как берётся
  комиссия.

  Всё «вокруг» — за этим behaviour. `TableServer` зовёт `GameMode` там, где
  начинается политика, и `Engine.Rules` там, где идёт раздача.
  """

  alias BlockPoker.Engine.HandSetup
  alias BlockPoker.Engine.PrizePool
  alias BlockPoker.Tables.RoomState
  alias BlockPoker.Tables.Seat

  @typedoc """
  Политика входа в игру: всё, что `Engine.EntryRules` нужно знать о столе
  сверх расклада мест.

  Вопрос «сколько стоит вступить в круг» принадлежит режиму, а не шаблону.
  В кэше игрок садится посреди игры и обязан заплатить за круг столько же,
  сколько платят сидящие. В турнире вопроса не существует: состав набран
  до первой раздачи и не меняется, поэтому политика вырождается в «входа
  не бывает» — и `dodge_window_hands` там ноль не потому, что окно
  короткое, а потому, что уклоняться от блайнда, не имея права встать,
  невозможно.
  """
  @type entry_policy :: %{
          big_blind: non_neg_integer(),
          allow_post_blind?: boolean(),
          dodge_window_hands: non_neg_integer(),
          immediate_entry?: boolean()
        }

  @doc """
  Дать режиму завести своё состояние в новой комнате.

  Существует, чтобы стол не спрашивал «а это турнир?»: он вызывает колбэк
  всегда, кэш возвращает комнату как есть, турнир заводит себе расписание
  уровней. Ветвление по режиму остаётся ровно там, где выбирается модуль.
  """
  @callback init_room(RoomState.t()) :: RoomState.t()

  @doc """
  Как режим называется в истории и статистике.

  Атом, а не строка и не вывод по имени модуля: по нему разрезаются
  агрегаты, и складывать строки разных режимов нечем — в кэше `net`
  измеряется деньгами, в турнире турнирными фишками. Ветвление по режиму
  остаётся ровно там, где выбирается модуль.
  """
  @callback game_mode_id() :: :cash | :sit_and_go | :mtt | :ofc_cash

  @doc """
  Таблица призовых тиров либо `nil`, если призового фонда у режима нет.

  Режим отвечает только «из чего тянуть»; тянет сам стол, потому что
  источник случайности принадлежит ему — по той же причине, по которой
  он бросает кубик бомб-пота.
  """
  @callback prize_table(RoomState.t()) :: [PrizePool.tier()] | nil

  @doc "Собрать вход раздачи: кто играет, с какими стеками и блайндами."
  @callback hand_setup(RoomState.t()) :: {:ok, HandSetup.t()} | {:error, :not_enough_players}

  @doc "Политика входа в игру: см. `t:entry_policy/0`."
  @callback entry_policy(RoomState.t()) :: entry_policy()

  @doc """
  Базовая единица стола: большой блайнд у блайндов, анте у анте кнопки.

  Режим, а не шаблон: в кэше номиналы неизменны и лежат в шаблоне, в
  турнире они растут и приходят из текущего уровня структуры.
  """
  @callback bet_unit(RoomState.t()) :: non_neg_integer()

  @doc """
  Стартует ли стол сам, собрав состав.

  В кэше это настройка (стол администратора ждёт ручного запуска), в
  турнире — всегда `true`: Sit & Go по определению начинается тогда, когда
  собрался пул, и ждать больше нечего.
  """
  @callback auto_start?(RoomState.t()) :: boolean()

  @doc """
  Номиналы стола, какими их видит игрок: малый и большой блайнды и анте.

  В кэше это поля шаблона, в турнире — текущий уровень структуры. Спрашивает
  их снапшот: выбирать между шаблоном и уровнем прямо во view значило бы
  завести там ветвление по режиму (§3 CLAUDE.md).
  """
  @callback limits(RoomState.t()) :: %{
              small_blind: non_neg_integer(),
              big_blind: non_neg_integer(),
              ante: non_neg_integer()
            }

  @doc """
  Тайминги стола: всё, по чему клиент рисует обратный отсчёт.

  Набор ключей у режимов разный, и это не оплошность: докупки и тайм-аута
  паузы в турнире не существует, а показывать нули вместо «механики нет»
  клиенту нельзя — он нарисует по ним счётчик.
  """
  @callback timings(RoomState.t()) :: map()

  @doc """
  Структура ставок стола: блайнды или анте кнопки.

  Её задаёт вид покера, но спрашивать шаблон напрямую снапшот не может —
  у режимов это разные структуры настроек. Режим знает свою.
  """
  @callback betting_structure(RoomState.t()) :: module()

  @doc "Название стола для экрана: у кэша это лимит, у турнира — шаблон турнира."
  @callback display_name(RoomState.t()) :: String.t()

  @doc """
  Сколько игроков должно собраться, чтобы стол начал игру.

  В кэше это двое — минимум, при котором покер возможен, и дальше стол
  играет любым составом. В Sit & Go число точное и равно вместимости:
  пул обязан собраться целиком, иначе структура мест и призов считалась
  бы от другого количества участников, чем то, за которое заплатили.
  """
  @callback start_threshold(RoomState.t()) :: pos_integer()

  @doc """
  Сколько игрок вправе просидеть в паузе, прежде чем стол вернёт ему фишки
  и освободит место. `nil` — механики нет.

  В турнире `nil`: место не освобождается никогда, потому что стек игрока
  есть часть структуры мест. Ушедший в паузу продолжает платить вынужденные
  ставки и складывать карты, пока не вылетит, — и это правило турнира,
  а не тайм-аут.
  """
  @callback sit_out_timeout_ms(RoomState.t()) :: pos_integer() | nil

  @doc """
  Сколько времени даётся на докупку после проигранного стека. `nil` —
  докупки не бывает, а нулевой стек означает вылет.
  """
  @callback rebuy_prompt_ms(RoomState.t()) :: pos_integer() | nil

  @doc """
  Допустима ли такая сумма фишек на столе перед игроком.

  Проверяется **итоговый стек**, а не сумма операции: в кэше он обязан
  укладываться в границы бай-ина шаблона, в турнире равен стартовому и
  ничему другому равен быть не может.
  """
  @callback validate_buy_in(RoomState.t(), non_neg_integer(), non_neg_integer()) ::
              :ok | {:error, :invalid_buy_in}

  @doc """
  Сколько фишек ещё можно доложить к такому стеку. `nil` — потолка нет.

  Нужна отложенной докупке: пока она ждала конца раздачи, стек мог вырасти,
  и заказанная сумма уже не влезает. Отказывать целиком в этот момент нечестно
  — деньги списаны, — поэтому докупка урезается до потолка, а остаток уходит
  назад в кошелёк. Граница спрашивается у режима по той же причине, что и
  `validate_buy_in/3`: в кэше её задаёт шаблон, в турнире доложить нельзя вовсе.
  """
  @callback max_add_chips(RoomState.t(), non_neg_integer()) :: non_neg_integer() | nil

  @doc "Раздача завершилась: раздать результаты, обновить состояние комнаты."
  @callback on_hand_finished(RoomState.t(), results :: term()) :: RoomState.t()

  @doc "Игрок остался без фишек: кэш предлагает докупиться, турнир — вылет."
  @callback on_zero_stack(RoomState.t(), Seat.t()) :: RoomState.t()

  @doc "Может ли игрок встать из-за стола прямо сейчас."
  @callback can_leave?(RoomState.t(), Seat.t()) :: boolean()

  @doc """
  Взять бай-ин. В кэше — списание из кошелька, в турнире фишки берутся
  из стартового стека, и денег это не касается вовсе.
  """
  @callback take_buy_in(RoomState.t(), Ecto.UUID.t(), pos_integer(), String.t()) ::
              :ok | {:error, atom()}

  @doc "Рейк с банка: в кэше по шаблону лимита, в турнире всегда 0."
  @callback rake(setting :: term(), pot :: non_neg_integer(), players :: pos_integer(), keyword()) ::
              non_neg_integer()

  @doc """
  Разрешён ли за этим столом run it twice.

  Кэш читает флаг шаблона; любой другой режим отвечает `false` **всегда**.
  В турнире фишка — это позиция в структуре мест, и дробление банка по
  прогонам меняет распределение мест, а не только дисперсию. Настройки
  «разрешить RIT» в турнирных структурах не заводится: решение принимается
  здесь и больше нигде.
  """
  @callback run_it_twice?(RoomState.t()) :: boolean()

  @doc """
  Разрешён ли за этим столом страддл.

  Кэш отвечает `true` всегда, любой другой режим — `false`. Ставка вслепую
  вне очереди осмысленна там, где фишки покупаются и продаются: игрок платит
  за банк своими деньгами и в любой момент может встать. В турнире тот же
  жест — это отказ от позиции в структуре мест, и решается он не настройкой
  стола, а тем, что режим его не предлагает вовсе.
  """
  @callback straddle?(RoomState.t()) :: boolean()

  @doc """
  Бомб-пот за этим столом: шанс раздачи без префлопа и взнос за неё —
  или `nil`, если механики нет.

  Кэш читает шаблон, любой другой режим отвечает `nil`. Причина та же, что
  у run it twice: бомб-пот меняет цену круга для всех сразу, и в турнире
  это была бы правка структуры блайндов посреди уровня, а не развлечение.

  Режим отвечает только «сколько и с каким шансом»; бросает кубик стол,
  потому что источник случайности принадлежит ему (`Engine.BombPot`).
  """
  @callback bomb_pot(RoomState.t()) ::
              %{chance: pos_integer(), ante: pos_integer()} | nil

  @typedoc """
  Итог участника: место, которое он занял, и выплата за него в минимальных
  единицах. Ноль означает место вне призовой зоны — это не ошибка и не
  отсутствие результата.
  """
  @type result :: %{
          user_id: Ecto.UUID.t(),
          seat: pos_integer(),
          place: pos_integer(),
          amount: non_neg_integer()
        }

  @doc """
  Закончилась ли игра за этим столом окончательно.

  Кэш отвечает `false` всегда: кэш-стол не заканчивается, он пустеет.
  Турнир заканчивается, когда живой остался один, — и это единственное
  состояние, из которого стол не продолжает игру.
  """
  @callback finished?(RoomState.t()) :: boolean()

  @doc """
  Итоговая таблица: кто какое место занял и сколько за него получит.

  Функция **чистая** — она только считает. Начисляет деньги вызывающий,
  потому что поход в кошелёк это I/O, а режим им не владеет (§3 CLAUDE.md).
  """
  @callback results(RoomState.t()) :: [result()]

  @doc """
  Правила бомб-пота для экрана: шанс, взнос и подпись — или `nil`.

  Отличается от `bomb_pot/1` тем, что описывает **стол**, а не решение по
  ближайшей раздаче: шанс постоянен, а выпавший взнос появляется только
  после броска.
  """
  @callback bomb_pot_view(RoomState.t()) :: map() | nil

  @doc "Вернуть фишки игроку: в кэше — cash-out в кошелёк, в турнире — no-op."
  @callback return_chips(RoomState.t(), Ecto.UUID.t(), non_neg_integer(), String.t()) ::
              :ok | {:error, atom()}
end
