defmodule BlockPoker.Engine.TimeBank do
  @moduledoc """
  Тайм-банк: личный запас времени игрока сверх обычного времени на ход.

  Правило одно и то же во всех форматах — кэш, турнир, sit-n-go, — потому
  что оно про **время**, а не про деньги. Отличаются только числа в шаблоне
  комнаты, и берутся они оттуда, а не из кода.

  Как это работает:

    1. На ход даётся `action_timeout_ms` — обычное время. Банк при этом
       не тратится вовсе: за фолд мусора платить своим запасом незачем.
    2. Обычное время кончилось, банк не пуст — включается банк, и игрок
       продолжает думать. Ход при этом **не делается автоматически**.
    3. Кончился и банк — стол ходит за игрока (чек, если бесплатно, иначе
       фолд). Молча стоять стол не может.
    4. Потрачено ровно столько, сколько игрок продумал сверх обычного
       времени: успел за секунду — секунда и списалась.
    5. За каждую сыгранную раздачу банк пополняется на `time_bank_refill`,
       но не выше `time_bank_ms`. Потолок обязателен: без него запас растёт
       у того, кто просто долго сидит за столом.

  Банк включается сам, а не по кнопке. Кнопка «использовать банк» — это
  лишнее решение в момент, когда игрок и так думает над раздачей; к тому же
  на лаге она приходит уже после автофолда.

  Модуль чистый: он не знает про часы и таймеры, ему передают прошедшее
  время. Всё, что здесь есть, — арифметика над остатком.
  """

  @type ms :: non_neg_integer()

  @doc "Стартовый запас: полный банк по шаблону комнаты."
  @spec initial(ms()) :: ms()
  def initial(max) when is_integer(max) and max >= 0, do: max
  def initial(_max), do: 0

  @doc "Есть ли чем продлить размышление."
  @spec available?(ms()) :: boolean()
  def available?(balance), do: is_integer(balance) and balance > 0

  @doc """
  Списание за прошедшее время. Больше остатка списать нельзя: когда банк
  дошёл до нуля, ход уже сделан за игрока, и «долга» не возникает.
  """
  @spec spend(ms(), ms()) :: ms()
  def spend(balance, elapsed) when is_integer(balance) and is_integer(elapsed) do
    balance |> Kernel.-(max(elapsed, 0)) |> max(0)
  end

  def spend(balance, _elapsed), do: balance

  @doc "Пополнение за сыгранную раздачу — до потолка, но не выше него."
  @spec refill(ms(), ms(), ms()) :: ms()
  def refill(balance, amount, max)
      when is_integer(balance) and is_integer(amount) and is_integer(max) do
    balance |> Kernel.+(max(amount, 0)) |> min(max(max, 0))
  end

  def refill(balance, _amount, _max), do: balance
end
