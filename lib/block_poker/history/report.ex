defmodule BlockPoker.History.Report do
  @moduledoc """
  Сырой отчёт о законченной раздаче: **копия данных**, которую стол отдаёт
  наружу и после которой про раздачу забывает.

  Копия, а не ссылка на состояние комнаты, — по требованию §6 задачи 6:
  `History.Writer` может отставать, упасть и перезапуститься, и на игру это
  не влияет никак. Обратной связи тоже нет: стол не обязан знать,
  записалась ли раздача.

  Сборкой строк отчёт не занимается — это делает `History.Build` уже в
  фоновом процессе. Здесь только то, что известно столу и больше нигде:
  идентификатор раздачи (заведён при её старте, на нём держится
  идемпотентность), номиналы **на момент раздачи**, лог событий с
  таймингами и результат эквити, посчитанный при олл-ине.

  Вида игры здесь нет намеренно: как называется раздача, знает она сама, и
  спрашивать её об этом обязана сборка, которая и так разбирает её по
  дисциплине. Столу пришлось бы ради этого ветвиться.
  """

  alias BlockPoker.Engine.Stats

  @type log_entry :: %{event: tuple(), at: integer(), auto?: boolean()}

  @type t :: %__MODULE__{}

  @enforce_keys [:hand_id, :room_id, :game_mode, :hand, :ended_at]
  defstruct [
    :hand_id,
    :room_id,
    :game_mode,
    :setting_id,
    :tournament_id,
    :level_number,
    :button_seat,
    :bomb_pot,
    :point_value,
    :started_at,
    :ended_at,
    # Законченная раздача дисциплины: по её типу `History.Build` и решает,
    # какие таблицы собирать.
    :hand,
    # Эквити на момент прекращения торговли. Считается один раз, при
    # олл-ине, и до конца раздачи доживает в комнате — второго расчёта
    # ради истории задача не вносит (§11 задачи 6).
    :equity,
    hand_number: 0,
    bet_unit: 0,
    small_blind: 0,
    big_blind: 0,
    ante: 0,
    log: [],
    # Прибавка показателей по местам: стол уже посчитал её для сессии,
    # и второй проход по событиям ради тех же чисел не нужен.
    stats: %{}
  ]

  @typedoc "Прибавка показателей одной раздачи по местам."
  @type stats :: %{pos_integer() => Stats.t()}
end
