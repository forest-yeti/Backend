defmodule BlockPoker.Engine.BettingStructure.BombPot do
  @moduledoc """
  Структура ставок бомб-пота: взнос со всех и никакого префлопа.

  Отличий от остальных структур ровно два, и оба следуют из механики
  (`Engine.BombPot`):

    * **Платят все и поровну.** Блайндов в этой раздаче нет вовсе — ни
      малого, ни большого, — поэтому и позиции «за блайндом» не существует.
      Взнос живой: он и есть ставка круга, которую все уже уравняли.
    * **Префлопа нет.** `last_to_act_preflop/1` возвращает `nil`: улицы, на
      которой кто-то говорит последним, не существует. Флоп открывается
      сразу после раздачи карманных карт, и порядок хода на нём общий для
      всех структур — первым говорит ближайший от кнопки.

  Кнопка при этом никуда не девается: она задаёт порядок хода на всех
  улицах и продолжает двигаться по кругу обычным порядком. Бомб-пот
  отменяет плату за позицию, а не саму позицию.

  Номинал круга — базовая единица стола (`max` блайнда и анте: на
  блайндовом столе это большой блайнд, на анте-столе — анте), а не размер
  взноса. Взнос бывает и в пять номиналов, и минимальная ставка на флопе
  от него не растёт: игроки уже заплатили за банк, а торговля идёт по
  обычной цене стола.
  """

  @behaviour BlockPoker.Engine.BettingStructure

  alias BlockPoker.Engine.EntryRules
  alias BlockPoker.Engine.HandSetup

  @impl true
  def id, do: :bomb_pot

  @impl true
  def bet_unit(%{big_blind: big_blind, ante: ante}), do: max(big_blind, ante)

  # Ждать нечего: взнос платят все и в этой раздаче, уклониться от своей
  # очереди невозможно — очереди нет. За столом эти правила всё равно
  # спрашивают у структуры стола: бомб-пот живёт одну раздачу и посадкой
  # не распоряжается.
  @impl true
  def entry_rules, do: EntryRules.Immediate

  # Префлопа нет — значит, нет и того, после кого он начинается.
  @impl true
  def last_to_act_preflop(%HandSetup{}), do: nil

  @impl true
  def forced_bets(%HandSetup{bomb_pot: %{ante: ante}} = setup) do
    setup
    |> HandSetup.order_from_button()
    |> Enum.map(&%{seat: &1.seat, kind: :bomb_pot_ante, amount: ante, live?: true})
  end
end
